-- ── event → สถานะจุดบกพร่อง (ผู้รับจ้างแก้ defects เองไม่ได้ จึงให้ trigger ทำ) ──
create or replace function apply_defect_event() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update defects set
    status   = case new.kind when 'created' then 'open' when 'fix_submitted' then 'submitted' else new.kind end,
    round_no = case when new.kind = 'fix_submitted' then round_no else new.round_no end
  where id = new.defect_id;
  return new;
end $$;
drop trigger if exists trg_defect_event on defect_events;
create trigger trg_defect_event after insert on defect_events for each row execute function apply_defect_event();

