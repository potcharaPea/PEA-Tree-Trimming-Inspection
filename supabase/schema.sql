-- ── การไฟฟ้า (เพิ่มแห่งใหม่ = insert แถวใหม่) ──
create table if not exists offices (
  id   text primary key,              -- รหัสสั้น ใช้ต่อท้ายอีเมลภายใน เช่น kce
  name text not null
);
insert into offices (id, name) values ('kce', 'กฟส.คำชะอี'), ('ktw', 'กฟส.กันทรวิชัย') on conflict (id) do nothing;

-- ── ผู้ใช้ (1 แถวต่อ 1 auth.users) ──
-- login ด้วยชื่อผู้ใช้: frontend แปลงเป็นอีเมลภายใน {username}@{office_id}.local
create table if not exists profiles (
  id        uuid primary key references auth.users on delete cascade,
  office_id text not null references offices,
  username  text not null,
  full_name text not null default '',
  role      text not null check (role in ('inspector', 'contractor')),
  company   text,                      -- ชื่อบริษัท/หจก. (ผู้รับจ้าง)
  is_admin  boolean not null default false,   -- ผู้ดูแลระบบ: เพิ่มการไฟฟ้า/ผู้ใช้ได้ทุกแห่ง
  unique (office_id, username)
);
alter table profiles add column if not exists is_admin boolean not null default false;   -- สำหรับฐานข้อมูลที่สร้างก่อนมีคอลัมน์นี้

create table if not exists feeders (
  id         uuid primary key default gen_random_uuid(),
  office_id  text not null references offices,
  code       text not null,
  line_name  text not null default '',
  created_by uuid references profiles default auth.uid(),
  created_at timestamptz not null default now(),
  closed_at  timestamptz,              -- สถานะอื่น (กำลังตรวจ/รอแก้) คำนวณที่ client
  unique (office_id, code)
);

create table if not exists feeder_contractors (
  feeder_id     uuid references feeders on delete cascade,
  contractor_id uuid references profiles on delete cascade,
  primary key (feeder_id, contractor_id)
);

create table if not exists segments (
  id              uuid primary key default gen_random_uuid(),
  feeder_id       uuid not null references feeders on delete cascade,
  seq             int  not null,
  source_file     text,
  voltage         text,
  plan_trees      int,
  density_label   text,
  density_range   text,
  price_trees     int,
  length_km       numeric not null default 0,
  geom_geojson    jsonb not null,      -- {"type":"LineString","coordinates":[[lng,lat],…]}
  raw_description text,
  passed_at       timestamptz,         -- "ผ่านทั้งช่วง"
  passed_by       uuid references profiles,
  unique (feeder_id, seq)
);

create table if not exists inspection_rounds (
  id           uuid primary key default gen_random_uuid(),
  feeder_id    uuid not null references feeders on delete cascade,
  round_no     int  not null,
  started_at   timestamptz not null default now(),
  inspector_id uuid references profiles default auth.uid(),
  unique (feeder_id, round_no)
);

create table if not exists defects (
  id         uuid primary key default gen_random_uuid(),
  code_no    bigint generated by default as identity,   -- แสดงเป็น D-0412
  segment_id uuid not null references segments on delete cascade,
  feeder_id  uuid not null references feeders on delete cascade,
  round_id   uuid references inspection_rounds on delete set null,
  round_no   int  not null default 1,                    -- รอบตรวจล่าสุด (trigger อัปเดต)
  lat        double precision not null,
  lng        double precision not null,
  issue_type text not null,
  note       text,
  status     text not null default 'open' check (status in ('open', 'submitted', 'passed', 'rejected')),
  created_by uuid references profiles default auth.uid(),
  created_at timestamptz not null default now()
);

create table if not exists defect_events (
  id         uuid primary key default gen_random_uuid(),
  defect_id  uuid not null references defects on delete cascade,
  kind       text not null check (kind in ('created', 'fix_submitted', 'passed', 'rejected')),
  round_no   int  not null,
  note       text,
  photos     jsonb not null default '[]',   -- [{"path":"MDA03R-04/<defect>/<event>_1.jpg","label":"IMG_1.jpg"}]
  actor_id   uuid references profiles default auth.uid(),
  created_at timestamptz not null default now()
);

-- ── งานตัดของผู้รับจ้าง (ก่อนตรวจรับ): started = เริ่มตัด + รูปก่อนตัด, finished = ตัดเสร็จ + รูปหลังตัด ──
create table if not exists segment_works (
  id         uuid primary key default gen_random_uuid(),   -- id มาจากเครื่อง (ส่งซ้ำตอน sync ได้)
  segment_id uuid not null references segments on delete cascade,
  feeder_id  uuid not null references feeders on delete cascade,
  kind       text not null check (kind in ('started', 'finished')),
  note       text,
  photos     jsonb not null default '[]',   -- [{"path":"MDA03R-04/<segment>/<work>_1.jpg","label":"IMG_1.jpg","lat":16.5,"lng":104.6}]
  actor_id   uuid references profiles default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz                      -- ผู้รับจ้างแก้ไขรายงานล่าสุดเมื่อ (null = ไม่เคยแก้)
);
alter table segment_works add column if not exists updated_at timestamptz;   -- สำหรับฐานข้อมูลที่สร้างก่อนมีคอลัมน์นี้

-- ── ขอดับไฟเพื่อตัดต้นไม้ (รายช่วง): ผู้รับจ้างขอ + เสนอวัน → ผู้ตรวจยืนยันวันดับไฟ หรือปฏิเสธ ──
create table if not exists outage_requests (
  id         uuid primary key default gen_random_uuid(),
  segment_id uuid not null references segments on delete cascade,
  feeder_id  uuid not null references feeders on delete cascade,
  want_date  date not null,                 -- วันที่ผู้รับจ้างขอ
  want_time  text not null default '',      -- ช่วงเวลา เช่น 09:00–12:00
  note       text,                          -- ตำแหน่ง/เหตุผล เช่น ต้นยางใหญ่คร่อมสาย เสาที่ 12–14
  status     text not null default 'requested' check (status in ('requested', 'confirmed', 'rejected')),
  ok_date    date,                          -- วันดับไฟที่ผู้ตรวจยืนยัน (อาจเลื่อนจากที่ขอ)
  ok_time    text,
  reply      text,                          -- ข้อความจากผู้ตรวจ / เหตุผลที่ปฏิเสธ
  actor_id   uuid references profiles default auth.uid(),
  created_at timestamptz not null default now(),
  decided_by uuid references profiles,
  decided_at timestamptz
);

create index if not exists segments_feeder_idx on segments (feeder_id);
